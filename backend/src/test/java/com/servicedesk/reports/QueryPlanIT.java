package com.servicedesk.reports;

import com.servicedesk.support.IntegrationTest;
import com.servicedesk.support.TestData;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Random;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfSystemProperty;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.simple.JdbcClient;

/**
 * Produces the EXPLAIN ANALYZE evidence in docs/sql/query-plans.md. Not part of the regular
 * suite (it seeds 60k tickets); run it on demand:
 *
 * <pre>mvn test -Dtest=QueryPlanIT -Dservicedesk.plans=true</pre>
 */
@IntegrationTest
@EnabledIfSystemProperty(named = "servicedesk.plans", matches = "true")
class QueryPlanIT {

    private static final int ORGS = 20;
    private static final int TICKETS = 60_000;

    @Autowired JdbcClient jdbc;
    @Autowired TestData data;

    @Test
    void explainRepresentativeQueries() throws IOException {
        data.reset();
        seed();
        StringBuilder out = new StringBuilder();
        out.append("# Query plans (EXPLAIN ANALYZE)\n\n")
           .append("Generated by `QueryPlanIT` against embedded PostgreSQL with ")
           .append(ORGS).append(" organizations and ").append(TICKETS).append(" tickets (~")
           .append(TICKETS / ORGS).append(" per organization). Each query is shown with the indexes from ")
           .append("`V1__init.sql` dropped and then restored, so the effect of each index is visible.\n\n");

        String listOpen = """
                SELECT t.* FROM tickets t
                WHERE t.organization_id = 7 AND t.status = 'OPEN'
                ORDER BY t.created_at DESC, t.id DESC
                LIMIT 20 OFFSET 0""";
        String byAssignee = """
                SELECT t.* FROM tickets t
                WHERE t.organization_id = 7 AND t.assignee_id = (SELECT MIN(assignee_id) FROM tickets WHERE organization_id = 7)
                ORDER BY t.created_at DESC
                LIMIT 20""";
        String workload = """
                SELECT u.id, u.full_name,
                       COUNT(t.id) FILTER (WHERE t.status IN ('OPEN','IN_PROGRESS')) AS active_assigned,
                       AVG(EXTRACT(EPOCH FROM (t.resolved_at - t.created_at)) / 3600.0)
                           FILTER (WHERE t.resolved_at >= now() - interval '30 days') AS avg_resolution_hours
                FROM memberships m
                JOIN users u ON u.id = m.user_id
                LEFT JOIN tickets t ON t.assignee_id = u.id AND t.organization_id = m.organization_id
                WHERE m.organization_id = 7 AND m.role IN ('TECHNICIAN','ADMIN')
                GROUP BY u.id, u.full_name""";

        section(out, "1. Ticket list filtered by status, newest first (the default screen)", listOpen,
                List.of("ix_tickets_org_status", "ix_tickets_org_created_at"));
        section(out, "2. Tickets assigned to one technician", byAssignee, List.of("ix_tickets_org_assignee"));
        section(out, "3. Workload per technician (dashboard)", workload, List.of("ix_tickets_org_assignee"));

        Path target = Path.of("target", "query-plans.md");
        Files.writeString(target, out);
        System.out.println("Query plans written to " + target.toAbsolutePath());
    }

    private void section(StringBuilder out, String title, String sql, List<String> indexes) {
        out.append("## ").append(title).append("\n\n```sql\n").append(sql).append("\n```\n\n");
        for (String ix : indexes) jdbc.sql("DROP INDEX " + ix).update();
        jdbc.sql("ANALYZE tickets").update();
        out.append("### Without ").append(String.join(", ", indexes)).append("\n\n```\n").append(explain(sql)).append("```\n\n");
        recreateIndexes(indexes);
        jdbc.sql("ANALYZE tickets").update();
        out.append("### With indexes\n\n```\n").append(explain(sql)).append("```\n\n");
    }

    private void recreateIndexes(List<String> indexes) {
        for (String ix : indexes) {
            String ddl = switch (ix) {
                case "ix_tickets_org_status" -> "CREATE INDEX ix_tickets_org_status ON tickets (organization_id, status)";
                case "ix_tickets_org_assignee" -> "CREATE INDEX ix_tickets_org_assignee ON tickets (organization_id, assignee_id)";
                case "ix_tickets_org_created_at" -> "CREATE INDEX ix_tickets_org_created_at ON tickets (organization_id, created_at DESC)";
                default -> throw new IllegalArgumentException(ix);
            };
            jdbc.sql(ddl).update();
        }
    }

    private String explain(String sql) {
        List<String> lines = jdbc.sql("EXPLAIN (ANALYZE, BUFFERS) " + sql).query(String.class).list();
        return String.join("\n", lines) + "\n";
    }

    private void seed() {
        jdbc.sql("INSERT INTO users (email, password_hash, full_name) SELECT 'u' || g || '@test.local', 'x', 'User ' || g FROM generate_series(1, :n) g")
                .param("n", ORGS * 6).update();
        jdbc.sql("INSERT INTO organizations (name, slug) SELECT 'Org ' || g, 'org-' || g FROM generate_series(1, :n) g")
                .param("n", ORGS).update();
        // 6 users per org: 1 admin, 2 technicians, 3 requesters
        jdbc.sql("""
                INSERT INTO memberships (user_id, organization_id, role)
                SELECT u, ((u - 1) / 6) + 1,
                       CASE (u - 1) % 6 WHEN 0 THEN 'ADMIN' WHEN 1 THEN 'TECHNICIAN' WHEN 2 THEN 'TECHNICIAN' ELSE 'REQUESTER' END
                FROM generate_series(1, :n) u""").param("n", ORGS * 6).update();
        Random random = new Random(42);
        StringBuilder values = new StringBuilder();
        for (int i = 1; i <= TICKETS; i++) {
            int org = random.nextInt(ORGS) + 1;
            int base = (org - 1) * 6;
            int requester = base + 4 + random.nextInt(3);
            String status = List.of("OPEN", "IN_PROGRESS", "RESOLVED", "CLOSED").get(random.nextInt(4));
            String assignee = status.equals("OPEN") && random.nextBoolean() ? "NULL" : String.valueOf(base + 2 + random.nextInt(2));
            int daysAgo = random.nextInt(365);
            String resolved = status.equals("RESOLVED") || status.equals("CLOSED")
                    ? "now() - interval '" + daysAgo + " days' + interval '" + (1 + random.nextInt(72)) + " hours'" : "NULL";
            values.append(values.isEmpty() ? "" : ",")
                  .append("(").append(org).append(",'Ticket ").append(i).append("','d','").append(status).append("','MEDIUM',")
                  .append(requester).append(",").append(assignee).append(",now() - interval '").append(daysAgo).append(" days',")
                  .append(resolved).append(")");
            if (i % 5000 == 0) {
                flush(values);
                values.setLength(0);
            }
        }
        if (!values.isEmpty()) flush(values);
    }

    private void flush(StringBuilder values) {
        jdbc.sql("INSERT INTO tickets (organization_id, title, description, status, priority, requester_id, assignee_id, created_at, resolved_at) VALUES "
                + values).update();
    }
}
